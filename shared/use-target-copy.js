export function targetMessage(api, key) {
  const language = api.i18n.getUILanguage().replace(/-/g, "_");
  const name = language.startsWith("zh")
    ? /TW|HK|Hant/i.test(language) ? "zh_TW" : "zh_CN"
    : language.split("_")[0];
  return copies[name]?.[key] ?? copies.en[key] ?? api.i18n.getMessage(key);
}

export function savedDeviceText(api, device) { return api.i18n.getMessage("savedOnDevice", [device.label]); }
